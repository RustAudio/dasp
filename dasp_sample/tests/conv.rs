/// A completeness check over the whole conversion matrix.
///
/// The blocks above are written out by hand, so a missing `FromSample` impl for some pair of
/// types would simply go untested rather than fail. This asserts that every ordered pair of
/// sample types converts at all (a missing impl is a compile error) and that equilibrium is
/// preserved in every direction, which is the one expectation that holds for all of them.
///
/// Add any new sample type to the single list in `every_pair_converts_and_preserves_equilibrium`.
mod matrix {
    use dasp_sample::{Sample, I24, I24BE3, I24LE3, I48, U24, U24BE3, U24LE3, U48};

    macro_rules! conv_row {
        ($n:ident; $A:ty; $($B:ty),*) => {$({
            let converted: $B = <$A as Sample>::EQUILIBRIUM.to_sample::<$B>();
            assert_eq!(
                converted,
                <$B as Sample>::EQUILIBRIUM,
                "{} -> {}: equilibrium was not preserved",
                stringify!($A),
                stringify!($B),
            );
            $n += 1;
        })*};
    }

    /// Expands to the conversions for every ordered pair, and evaluates to the number of types
    /// in the list.
    ///
    /// The list is given once and expanded along *both* dimensions, which is the point: an
    /// earlier version of this test wrote the target types out a second time, and comparing the
    /// pair count against `types * types` then only proved the two lists were the same length.
    /// Swapping one type for another in just one of them passed while leaving that type
    /// untested and its replacement tested twice. With a single list that cannot happen.
    macro_rules! conv_matrix {
        ($n:ident; $($T:ty),*) => {{
            conv_matrix!(@rows $n; [$($T),*]; $($T),*);
            [$(stringify!($T)),*].len()
        }};
        // Peel one type off the outer list at a time so the whole inner list can be expanded
        // again for each row. A single `$( conv_row!(.. $A .. $($B),*); )*` is not legal: both
        // lists sit at the same repetition depth, so rustc tries to iterate them in lockstep.
        (@rows $n:ident; [$($B:ty),*]; $A:ty $(, $rest:ty)*) => {
            conv_row!($n; $A; $($B),*);
            conv_matrix!(@rows $n; [$($B),*]; $($rest),*);
        };
        (@rows $n:ident; [$($B:ty),*];) => {};
    }

    #[test]
    fn every_pair_converts_and_preserves_equilibrium() {
        let mut n = 0usize;
        let types = conv_matrix!(n; i8, i16, I24, I24LE3, I24BE3, i32, I48, i64,
                                    u8, u16, U24, U24LE3, U24BE3, u32, U48, u64, f32, f64);
        assert_eq!(
            n,
            types * types,
            "expected every ordered pair of {types} sample types"
        );
        assert_eq!(
            types, 18,
            "a sample type was added or removed without updating this count"
        );
    }
}
